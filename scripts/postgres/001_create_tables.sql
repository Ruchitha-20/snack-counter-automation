-- Snack Counter Automation: PostgreSQL schema
-- Run this file against the database where you want to create the tables.
-- The script is safe to re-run.

BEGIN;

CREATE SCHEMA IF NOT EXISTS snack_counter;

CREATE TABLE IF NOT EXISTS snack_counter.office (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL UNIQUE,
    currency_code   CHAR(3) NOT NULL,
    monthly_budget  NUMERIC(12, 2) NOT NULL CHECK (monthly_budget > 0),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS snack_counter.employee (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code   VARCHAR(50) NOT NULL UNIQUE,
    full_name       VARCHAR(150) NOT NULL,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- An employee can belong to a home office and temporarily be assigned
-- to another office while visiting. Keep one row per employee/office pair.
CREATE TABLE IF NOT EXISTS snack_counter.employee_office_membership (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     BIGINT NOT NULL REFERENCES snack_counter.employee(id) ON DELETE CASCADE,
    office_id       BIGINT NOT NULL REFERENCES snack_counter.office(id) ON DELETE CASCADE,
    membership_type VARCHAR(10) NOT NULL CHECK (membership_type IN ('HOME', 'VISITING')),
    valid_from      DATE NOT NULL DEFAULT CURRENT_DATE,
    valid_until     DATE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_employee_office_membership UNIQUE (employee_id, office_id),
    CONSTRAINT ck_membership_dates CHECK (valid_until IS NULL OR valid_until >= valid_from)
);

CREATE TABLE IF NOT EXISTS snack_counter.volunteer_availability (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     BIGINT NOT NULL REFERENCES snack_counter.employee(id) ON DELETE CASCADE,
    office_id       BIGINT NOT NULL REFERENCES snack_counter.office(id) ON DELETE CASCADE,
    is_available   BOOLEAN NOT NULL DEFAULT TRUE,
    available_from  DATE NOT NULL DEFAULT CURRENT_DATE,
    available_until DATE,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_volunteer_availability UNIQUE (employee_id, office_id),
    CONSTRAINT ck_availability_dates CHECK (available_until IS NULL OR available_until >= available_from)
);

CREATE TABLE IF NOT EXISTS snack_counter.snack_box (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_id       BIGINT NOT NULL REFERENCES snack_counter.office(id),
    name            VARCHAR(150) NOT NULL,
    location_note   VARCHAR(255),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_snack_box_office_name UNIQUE (office_id, name)
);

CREATE TABLE IF NOT EXISTS snack_counter.refill_request (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snack_box_id        BIGINT NOT NULL REFERENCES snack_counter.snack_box(id),
    reported_by         BIGINT REFERENCES snack_counter.employee(id),
    status              VARCHAR(20) NOT NULL DEFAULT 'OPEN'
                        CHECK (status IN ('OPEN', 'ASSIGNED', 'ACCEPTED', 'PURCHASED', 'CLAIM_SUBMITTED', 'CLOSED', 'CANCELLED')),
    reported_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    assigned_employee_id BIGINT REFERENCES snack_counter.employee(id),
    completed_at        TIMESTAMPTZ,
    notes               TEXT
);

-- Prevent multiple simultaneously active refill requests for the same box.
CREATE UNIQUE INDEX IF NOT EXISTS uq_refill_request_active_box
    ON snack_counter.refill_request (snack_box_id)
    WHERE status IN ('OPEN', 'ASSIGNED', 'ACCEPTED');

CREATE INDEX IF NOT EXISTS idx_refill_request_status_reported
    ON snack_counter.refill_request (status, reported_at DESC);

CREATE TABLE IF NOT EXISTS snack_counter.refill_assignment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refill_request_id BIGINT NOT NULL REFERENCES snack_counter.refill_request(id) ON DELETE CASCADE,
    employee_id     BIGINT NOT NULL REFERENCES snack_counter.employee(id),
    status          VARCHAR(15) NOT NULL DEFAULT 'ASSIGNED'
                    CHECK (status IN ('ASSIGNED', 'ACCEPTED', 'DECLINED', 'EXPIRED', 'COMPLETED')),
    assigned_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at      TIMESTAMPTZ NOT NULL,
    accepted_at     TIMESTAMPTZ,
    closed_at       TIMESTAMPTZ,
    CONSTRAINT ck_assignment_expiry CHECK (expires_at > assigned_at)
);

-- A volunteer may have at most one active assignment at a time.
CREATE UNIQUE INDEX IF NOT EXISTS uq_refill_assignment_active_employee
    ON snack_counter.refill_assignment (employee_id)
    WHERE status IN ('ASSIGNED', 'ACCEPTED');

CREATE INDEX IF NOT EXISTS idx_refill_assignment_request
    ON snack_counter.refill_assignment (refill_request_id, assigned_at DESC);

CREATE TABLE IF NOT EXISTS snack_counter.office_monthly_budget (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_id       BIGINT NOT NULL REFERENCES snack_counter.office(id) ON DELETE CASCADE,
    budget_month    DATE NOT NULL,
    currency_code   CHAR(3) NOT NULL,
    budget_amount   NUMERIC(12, 2) NOT NULL CHECK (budget_amount >= 0),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_budget_month_start CHECK (EXTRACT(DAY FROM budget_month) = 1),
    CONSTRAINT uq_office_monthly_budget UNIQUE (office_id, budget_month)
);

-- Reservations prevent two concurrent purchases from using the same remaining
-- budget. The application should create/consume a reservation in a DB transaction.
CREATE TABLE IF NOT EXISTS snack_counter.budget_reservation (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_id           BIGINT NOT NULL REFERENCES snack_counter.office(id),
    budget_month        DATE NOT NULL,
    refill_request_id   BIGINT NOT NULL REFERENCES snack_counter.refill_request(id),
    reserved_amount     NUMERIC(12, 2) NOT NULL CHECK (reserved_amount > 0),
    status              VARCHAR(12) NOT NULL DEFAULT 'RESERVED'
                        CHECK (status IN ('RESERVED', 'CONSUMED', 'RELEASED')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_reservation_month_start CHECK (EXTRACT(DAY FROM budget_month) = 1),
    CONSTRAINT uq_budget_reservation_request UNIQUE (refill_request_id)
);

CREATE INDEX IF NOT EXISTS idx_budget_reservation_month_status
    ON snack_counter.budget_reservation (office_id, budget_month, status);

CREATE TABLE IF NOT EXISTS snack_counter.purchase (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refill_request_id   BIGINT NOT NULL UNIQUE REFERENCES snack_counter.refill_request(id),
    employee_id         BIGINT NOT NULL REFERENCES snack_counter.employee(id),
    office_id           BIGINT NOT NULL REFERENCES snack_counter.office(id),
    purchase_amount     NUMERIC(12, 2) NOT NULL CHECK (purchase_amount > 0),
    currency_code       CHAR(3) NOT NULL,
    description         TEXT NOT NULL,
    purchased_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    budget_month        DATE NOT NULL,
    CONSTRAINT ck_purchase_month_start CHECK (EXTRACT(DAY FROM budget_month) = 1)
);

CREATE INDEX IF NOT EXISTS idx_purchase_office_month
    ON snack_counter.purchase (office_id, budget_month);

CREATE TABLE IF NOT EXISTS snack_counter.reimbursement_claim (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id         BIGINT NOT NULL UNIQUE REFERENCES snack_counter.purchase(id),
    employee_id         BIGINT NOT NULL REFERENCES snack_counter.employee(id),
    claim_amount        NUMERIC(12, 2) NOT NULL CHECK (claim_amount > 0),
    currency_code       CHAR(3) NOT NULL,
    status              VARCHAR(20) NOT NULL DEFAULT 'CLAIM_SUBMITTED'
                        CHECK (status IN ('CLAIM_SUBMITTED', 'APPROVED', 'REJECTED', 'REIMBURSED')),
    submitted_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolved_at         TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_claim_employee_status
    ON snack_counter.reimbursement_claim (employee_id, status);

COMMIT;
